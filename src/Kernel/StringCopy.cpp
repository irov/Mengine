#include "Kernel/StringCopy.h"

#include "Config/StdString.h"

namespace Mengine
{
    //////////////////////////////////////////////////////////////////////////
    namespace Helper
    {
        //////////////////////////////////////////////////////////////////////////
        void stringCopy( Char * const _dst, const Char * _src )
        {
            StdString::strcpy( _dst, _src );
        }
        //////////////////////////////////////////////////////////////////////////
        void stringCopy( WChar * const _dst, const WChar * _src )
        {
            StdString::wcscpy( _dst, _src );
        }
        //////////////////////////////////////////////////////////////////////////
    }
    //////////////////////////////////////////////////////////////////////////
}
