#include "MacOSFindPython3Plugin.h"

#include "Interface/ServiceInterface.h"

#include "Kernel/DocumentHelper.h"
#include "Kernel/PluginHelper.h"

//////////////////////////////////////////////////////////////////////////
SERVICE_EXTERN( FindPython3Service );
//////////////////////////////////////////////////////////////////////////
PLUGIN_FACTORY( MacOSFindPython3, Mengine::MacOSFindPython3Plugin );
//////////////////////////////////////////////////////////////////////////
namespace Mengine
{
    //////////////////////////////////////////////////////////////////////////
    MacOSFindPython3Plugin::MacOSFindPython3Plugin()
    {
    }
    //////////////////////////////////////////////////////////////////////////
    MacOSFindPython3Plugin::~MacOSFindPython3Plugin()
    {
    }
    //////////////////////////////////////////////////////////////////////////
    bool MacOSFindPython3Plugin::_initializePlugin()
    {
        if( SERVICE_CREATE( FindPython3Service, MENGINE_DOCUMENT_FACTORABLE ) == false )
        {
            return false;
        }

        return true;
    }
    //////////////////////////////////////////////////////////////////////////
    void MacOSFindPython3Plugin::_finalizePlugin()
    {
        SERVICE_FINALIZE( FindPython3Service );
    }
    //////////////////////////////////////////////////////////////////////////
    void MacOSFindPython3Plugin::_destroyPlugin()
    {
        SERVICE_DESTROY( FindPython3Service );
    }
    //////////////////////////////////////////////////////////////////////////
}
