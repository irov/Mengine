#include "Option.h"

namespace Mengine
{
    //////////////////////////////////////////////////////////////////////////
    Option::Option()
        : m_valueCount( 0 )
        , m_protected( false )
    {
    }
    //////////////////////////////////////////////////////////////////////////
    Option::~Option()
    {
    }
    //////////////////////////////////////////////////////////////////////////
    void Option::setKey( const Char * _key )
    {
        m_key.assign( _key );
    }
    //////////////////////////////////////////////////////////////////////////
    void Option::setKey( const Char * _key, size_t _size )
    {
        m_key.assign( _key, _size );
    }
    //////////////////////////////////////////////////////////////////////////
    void Option::addValue( const Char * _value )
    {
        m_values[m_valueCount].assign( _value );
        ++m_valueCount;
    }
    //////////////////////////////////////////////////////////////////////////
    void Option::addValue( const Char * _value, size_t _size )
    {
        m_values[m_valueCount].assign( _value, _size );
        ++m_valueCount;
    }
    //////////////////////////////////////////////////////////////////////////
    void Option::setProtected( bool _protected )
    {
        m_protected = _protected;
    }
    //////////////////////////////////////////////////////////////////////////
    const Char * Option::getKey() const
    {
        return m_key.c_str();
    }
    //////////////////////////////////////////////////////////////////////////
    const Char * Option::getValue( uint32_t _index ) const
    {
        return m_values[_index].c_str();
    }
    //////////////////////////////////////////////////////////////////////////
    uint32_t Option::getValueCount() const
    {
        return m_valueCount;
    }
    //////////////////////////////////////////////////////////////////////////
    bool Option::isProtected() const
    {
        return m_protected;
    }
    //////////////////////////////////////////////////////////////////////////
}
